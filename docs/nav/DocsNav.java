import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * Generates both documentation navigations from the {@code :page-nav-*:} attributes in each page of
 * {@code site/content}: the Roq data file {@code site/data/nav.yml} and the Antora
 * {@code docs/modules/ROOT/nav.adoc}.
 *
 * <p>Each page declares {@code :page-nav-group:} and {@code :page-nav-order:}, and optionally
 * {@code :page-nav-title:} (default: {@code :page-title:}, then the document heading). Groups appear in
 * the order of their lowest page. A page without the two required attributes fails the build.
 *
 * <p>Usage: {@code java docs/nav/DocsNav.java <repository root>}
 */
public final class DocsNav {

  private static final String GROUP = "page-nav-group";
  private static final String ORDER = "page-nav-order";
  private static final String NAV_TITLE = "page-nav-title";
  private static final String PAGE_TITLE = "page-title";
  private static final String NOTICE = "Generated by docs/nav/DocsNav.java from the :page-nav-*: attributes in site/content. Do not edit.";

  record Page(String path, String group, int order, String title) {}

  public static void main(String[] args) throws IOException {
    if (args.length != 1) {
      System.err.println("Usage: java DocsNav.java <repository root>");
      System.exit(2);
    }
    Path root = Path.of(args[0]);
    List<String> errors = new ArrayList<>();
    List<Page> pages = readPages(root, errors);
    if (!errors.isEmpty()) {
      errors.forEach(System.err::println);
      System.exit(1);
    }
    Map<String, List<Page>> groups = groupPages(pages);
    write(root.resolve("site/data/nav.yml"), roqData(groups));
    write(root.resolve("docs/modules/ROOT/nav.adoc"), antoraNav(groups));
  }

  static List<Page> readPages(Path root, List<String> errors) throws IOException {
    List<Path> files;
    try (Stream<Path> stream = Files.list(root.resolve("site/content"))) {
      files = stream.filter(p -> p.getFileName().toString().endsWith(".adoc")).sorted().toList();
    }
    List<Page> pages = new ArrayList<>();
    for (Path file : files) {
      readPage(root, file, errors).ifPresent(pages::add);
    }
    return pages;
  }

  private static Optional<Page> readPage(Path root, Path file, List<String> errors) throws IOException {
    String name = root.relativize(file).toString();
    Map<String, String> header = header(Files.readAllLines(file));
    String path = file.getFileName().toString().replaceFirst("\\.adoc$", "");
    boolean valid = true;
    if (header.getOrDefault(GROUP, "").isBlank()) {
      errors.add(name + ": missing :" + GROUP + ": (the sidebar group this page belongs to)");
      valid = false;
    }
    int order = 0;
    String rawOrder = header.getOrDefault(ORDER, "").strip();
    if (rawOrder.isEmpty()) {
      errors.add(name + ": missing :" + ORDER + ": (an integer that sorts the page in the navigation)");
      valid = false;
    } else {
      try {
        order = Integer.parseInt(rawOrder);
      } catch (NumberFormatException e) {
        errors.add(name + ": :" + ORDER + ": must be an integer, found '" + rawOrder + "'");
        valid = false;
      }
    }
    String title = firstNonBlank(header.get(NAV_TITLE), header.get(PAGE_TITLE), header.get("="));
    if (title.isBlank()) {
      errors.add(name + ": no title (add :" + NAV_TITLE + ":, :" + PAGE_TITLE + ": or a '= ' heading)");
      valid = false;
    }
    if (!valid) {
      return Optional.empty();
    }
    return Optional.of(new Page(path, header.get(GROUP).strip(), order, title.strip()));
  }

  private static Map<String, String> header(List<String> lines) {
    Map<String, String> header = new LinkedHashMap<>();
    for (String line : lines) {
      if (line.isBlank() && !header.isEmpty()) {
        break;
      }
      if (line.startsWith("= ")) {
        header.put("=", line.substring(2));
      } else if (line.startsWith(":") && line.indexOf(':', 1) > 0) {
        int end = line.indexOf(':', 1);
        header.put(line.substring(1, end), line.substring(end + 1).strip());
      }
    }
    return header;
  }

  private static String firstNonBlank(String... values) {
    for (String value : values) {
      if (value != null && !value.isBlank()) {
        return value;
      }
    }
    return "";
  }

  static Map<String, List<Page>> groupPages(List<Page> pages) {
    List<Page> sorted = pages.stream()
        .sorted(Comparator.comparingInt(Page::order).thenComparing(Page::path))
        .toList();
    Map<String, List<Page>> groups = new LinkedHashMap<>();
    for (Page page : sorted) {
      groups.computeIfAbsent(page.group(), g -> new ArrayList<>()).add(page);
    }
    return groups;
  }

  static String roqData(Map<String, List<Page>> groups) {
    StringBuilder out = new StringBuilder("# ").append(NOTICE).append("\ngroups:\n");
    groups.forEach((group, pages) -> {
      out.append("  - title: ").append(scalar(group)).append("\n    pages:\n");
      for (Page page : pages) {
        out.append("      - path: ").append(page.path()).append('\n');
        out.append("        file: ").append(page.path()).append(".adoc\n");
        out.append("        title: ").append(scalar(page.title())).append('\n');
      }
    });
    return out.toString();
  }

  static String antoraNav(Map<String, List<Page>> groups) {
    StringBuilder out = new StringBuilder("// ").append(NOTICE).append("\n");
    groups.forEach((group, pages) -> {
      out.append("\n[.list-top-item]\n.").append(group).append("\n\n");
      for (Page page : pages) {
        out.append("* xref:").append(page.path()).append(".adoc[").append(page.title()).append("]\n");
      }
    });
    out.append("\n[.list-top-item]\n.Development\n\n");
    out.append("* https://github.com/omatheusmesmo/qlawkus[Source Code^,role=github]\n");
    out.append("* https://github.com/omatheusmesmo/qlawkus/issues[Issues^,role=github]\n");
    return out.toString();
  }

  private static String scalar(String value) {
    boolean plain = !value.contains(": ") && !value.contains(" #") && !value.endsWith(":")
        && "[{&*!|>'\"%@`#,".indexOf(value.charAt(0)) < 0;
    return plain ? value : '"' + value.replace("\\", "\\\\").replace("\"", "\\\"") + '"';
  }

  private static void write(Path file, String content) throws IOException {
    Files.createDirectories(file.getParent());
    if (Files.exists(file) && Files.readString(file).equals(content)) {
      return;
    }
    Files.writeString(file, content);
  }
}
